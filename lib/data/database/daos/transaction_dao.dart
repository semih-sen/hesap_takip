/// DAO-level base-currency aggregates produced by
/// [TransactionDao.watchSummaryBuckets] — the raw building blocks the repository
/// assembles into the feature's `SummaryData`. A deliberately local value type
/// (no feature imports) so the DAO stays free of the presentation layer. Every
/// field is base-currency minor units.
///
/// The four in-period buckets are unsigned totals (transfers excluded); the
/// three `*Signed` fields are net running-balance flows (inflow + / outflow −)
/// that DO include completed transfer legs (Decision 2A).
class SummaryBuckets {
  const SummaryBuckets({
    required this.collectedIncomeMinor,
    required this.receivableIncomeMinor,
    required this.paidExpenseMinor,
    required this.payableExpenseMinor,
    required this.carriedNonTransferSignedMinor,
    required this.carriedTransferSignedMinor,
    required this.cashFlowSignedMinor,
    required this.inPeriodTransferSignedMinor,
  });

  /// income + completed, valueDate in period (Tahsilat).
  final int collectedIncomeMinor;

  /// income + pending, valueDate in period (Alacak).
  final int receivableIncomeMinor;

  /// expense + completed, valueDate in period (Ödeme).
  final int paidExpenseMinor;

  /// expense + pending, valueDate in period (Borç).
  final int payableExpenseMinor;

  /// (income+expense) completed|pending, valueDate < start, signed by flow.
  final int carriedNonTransferSignedMinor;

  /// transfer completed, valueDate < start, signed by flow (Decision 2A).
  final int carriedTransferSignedMinor;

  /// all types completed, valueDate <= today, signed by flow (cash basis).
  final int cashFlowSignedMinor;

  /// transfer completed, valueDate in period, signed by flow (Decision 2A).
  final int inPeriodTransferSignedMinor;
}

/// One category chip carried on a [TransactionListRowData]: enough to render a
/// color dot + name in Row 3 of the bespoke list item, with no follow-up query.
class TransactionRowCategory {
  const TransactionRowCategory({
    required this.id,
    required this.name,
    required this.colorValue,
  });

  final int id;
  final String name;
  final int colorValue;
}

/// Denormalized read-model for one transaction-list row, produced by the joined
/// query in [TransactionDao.watchTransactionListRows] (transaction ⨝ wallet ⨝
/// primary category). It carries exactly what the bespoke row needs, avoiding an
/// N+1 of per-row category/wallet lookups. The application layer maps it to the
/// presentational `TransactionListRow` view-model.
class TransactionListRowData {
  const TransactionListRowData({
    required this.id,
    required this.walletId,
    required this.type,
    required this.flowDirection,
    required this.status,
    required this.amountMinor,
    required this.currencyCode,
    required this.valueDate,
    required this.walletName,
    this.note,
    this.payee,
    this.categories = const <TransactionRowCategory>[],
    this.plannedAmountMinor,
    this.settledAmountMinor,
    this.isPendingParent = false,
    this.counterWalletName,
    this.isRecurring = false,
  });

  final int id;
  final int walletId;
  final TransactionType type;
  final FlowDirection flowDirection;
  final TransactionStatus status;
  final int amountMinor;
  final String currencyCode;
  final DateTime valueDate;
  final String walletName;
  final String? note;
  final String? payee;

  /// The transaction's categories (id + name + color) ordered primary-first
  /// (lowest `sortOrder`, then lowest id). Empty when it has no category links.
  /// The first entry drives the row's accent and title.
  final List<TransactionRowCategory> categories;

  // ---- Contextual Row-3 seams (PROJECT_PLAN §10.3) ----
  // These carry what later phases populate. They default to null/false today so
  // Phases 8–10 only need to start filling them (no schema/shape change here).

  /// Parent-bill planned/settled totals (Phase 9). Non-null only on parent rows.
  final int? plannedAmountMinor;
  final int? settledAmountMinor;

  /// True when this is a pending parent bill carrying a plan (Phase 9).
  final bool isPendingParent;

  /// The other leg's wallet name on a transfer (Phase 8); null otherwise.
  final String? counterWalletName;

  /// True when generated by a recurring rule (Phase 10).
  final bool isRecurring;
}

