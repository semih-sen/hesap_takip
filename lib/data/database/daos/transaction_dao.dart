  /// Links a category to a transaction (`allocatedAmountMinor == null` means the
  /// category covers the whole transaction).
  Future<void> addCategory(
    int transactionId,
    int categoryId, {
    int? allocatedAmountMinor,
  }) {
    return into(transactionCategories).insert(
      TransactionCategoriesCompanion.insert(
        transactionId: transactionId,
        categoryId: categoryId,
        allocatedAmountMinor: Value(allocatedAmountMinor),
      ),
    );
  }

  /// Replaces ALL category links for [transactionId] with [links] — deletes the
  /// existing set, then inserts the new one. Idempotent for a given [links] set.
  /// Callers that also mutate the transaction row wrap this in one
  /// `db.transaction(...)` for atomicity (see `TransactionRepository`).
  Future<void> replaceCategoryLinks(
    int transactionId,
    List<TransactionCategoriesCompanion> links,
  ) async {
    await (delete(
      transactionCategories,
    )..where((t) => t.transactionId.equals(transactionId))).go();
    if (links.isEmpty) {
      return;
    }
    await batch((Batch b) => b.insertAll(transactionCategories, links));
  }

  /// Field/record separators packing each transaction's category chips into one
  /// `group_concat` cell (`id␟color␟name`, chips joined by `␞`). Both are ASCII
  /// control chars (unit/record separator) that cannot occur in a category name,
  /// so parsing is unambiguous. Emitted in SQL via `char(31)` / `char(30)`.
  static final String _fieldSep = String.fromCharCode(31);
  static final String _recordSep = String.fromCharCode(30);

  static const DateOnlyConverter _dateOnly = DateOnlyConverter();

  /// Reactive, newest-first denormalized rows for the List scope, applying every
  /// predicate of [filter] **in SQL** (PROJECT_PLAN §9) and bounding the result
  /// to [limit] rows for the growing-window pagination (§10 / Phase 6). One
  /// query per row: the wallet is joined and the transaction's category chips
  /// are aggregated with `group_concat`, so there is no N+1.
  ///
  /// `readsFrom` registers every table the projection/predicates depend on, so
  /// the stream re-emits when a transaction, wallet, category, or link changes.
  Stream<List<TransactionListRowData>> watchTransactionRows(
    TransactionFilter filter, {
    required int limit,
  }) {
    final List<String> where = <String>[];
    final List<Variable> vars = <Variable>[];

    final DateRange? range = filter.range;
    if (range != null) {
      // value_date is ISO 'yyyy-MM-dd' text, so lexical compare == chronological.
      where.add('t.value_date >= ? AND t.value_date <= ?');
      vars.add(Variable.withString(_dateOnly.toSql(range.start)));
      vars.add(Variable.withString(_dateOnly.toSql(range.end)));
    }
    if (filter.walletIds.isNotEmpty) {
      final List<int> ids = filter.walletIds.toList();
      where.add('t.wallet_id IN (${_placeholders(ids.length)})');
      vars.addAll(ids.map(Variable.withInt));
    }
    if (filter.categoryIds.isNotEmpty) {
      final List<int> ids = filter.categoryIds.toList();
      where.add(
        'EXISTS (SELECT 1 FROM transaction_categories tcf '
        'WHERE tcf.transaction_id = t.id '
        'AND tcf.category_id IN (${_placeholders(ids.length)}))',
      );
      vars.addAll(ids.map(Variable.withInt));
    }
    if (filter.type != null) {
      where.add('t.type = ?');
      vars.add(Variable.withInt(filter.type!.index));
    }
    if (filter.status != null) {
      where.add('t.status = ?');
      vars.add(Variable.withInt(filter.status!.index));
    }
    final String query = filter.search.trim();
    if (query.isNotEmpty) {
      final String like = '%${_escapeLike(query)}%';
      where.add(
        r"(t.note LIKE ? ESCAPE '\' "
        r"OR t.payee LIKE ? ESCAPE '\' "
        'OR EXISTS (SELECT 1 FROM transaction_categories tcs '
        'JOIN categories cs ON cs.id = tcs.category_id '
        r"WHERE tcs.transaction_id = t.id AND cs.name LIKE ? ESCAPE '\'))",
      );
      vars
        ..add(Variable.withString(like))
        ..add(Variable.withString(like))
        ..add(Variable.withString(like));
    }

    final String whereSql = where.isEmpty
        ? ''
        : 'WHERE ${where.join(' AND ')} ';
    vars.add(Variable.withInt(limit));

    return customSelect(
      'SELECT t.id AS id, t.wallet_id AS wallet_id, t.type AS type, '
      't.flow_direction AS flow_direction, t.status AS status, '
      't.amount_minor AS amount_minor, t.currency_code AS currency_code, '
      't.value_date AS value_date, t.note AS note, t.payee AS payee, '
      't.planned_amount_minor AS planned_amount_minor, '
      't.settled_amount_minor AS settled_amount_minor, '
      't.recurring_rule_id AS recurring_rule_id, '
      't.transfer_group_id AS transfer_group_id, '
      'w.name AS wallet_name, '
      // The other leg's wallet name (Phase 8): the row in the same transfer
      // group with a different id. Null for non-transfer rows.
      '(SELECT w2.name FROM transactions t2 '
      '  JOIN wallets w2 ON w2.id = t2.wallet_id '
      '  WHERE t2.transfer_group_id = t.transfer_group_id '
      '  AND t2.id <> t.id LIMIT 1) AS counter_wallet_name, '
      '(SELECT group_concat(chip, char(30)) FROM ('
      '  SELECT (c.id || char(31) || c.color_value || char(31) || c.name) '
      '    AS chip '
      '  FROM transaction_categories tc '
      '  JOIN categories c ON c.id = tc.category_id '
      '  WHERE tc.transaction_id = t.id '
      '  ORDER BY c.sort_order, c.id'
      ')) AS categories_blob '
      'FROM transactions t '
      'JOIN wallets w ON w.id = t.wallet_id '
      '$whereSql'
      'ORDER BY t.value_date DESC, t.id DESC '
      'LIMIT ?',
      variables: vars,
      readsFrom: <ResultSetImplementation<dynamic, dynamic>>{
        transactions,
        wallets,
        categories,
        transactionCategories,
      },
    ).watch().map(
      (List<QueryRow> rows) => rows.map(_mapListRow).toList(growable: false),
    );
  }

  TransactionListRowData _mapListRow(QueryRow row) {
    final int statusIndex = row.read<int>('status');
    final TransactionStatus status = TransactionStatus.values[statusIndex];
    final int? planned = row.read<int?>('planned_amount_minor');
    return TransactionListRowData(
      id: row.read<int>('id'),
      walletId: row.read<int>('wallet_id'),
      type: TransactionType.values[row.read<int>('type')],
      flowDirection: FlowDirection.values[row.read<int>('flow_direction')],
      status: status,
      amountMinor: row.read<int>('amount_minor'),
      currencyCode: row.read<String>('currency_code'),
      // value_date is stored as ISO 'yyyy-MM-dd' text (DateOnlyConverter).
      valueDate: DateTime.parse(row.read<String>('value_date')),
      walletName: row.read<String>('wallet_name'),
      note: row.read<String?>('note'),
      payee: row.read<String?>('payee'),
      categories: _parseChips(row.read<String?>('categories_blob')),
      plannedAmountMinor: planned,
      settledAmountMinor: row.read<int?>('settled_amount_minor'),
      isPendingParent: status == TransactionStatus.pending && planned != null,
      isRecurring: row.read<int?>('recurring_rule_id') != null,
      // The other transfer leg's wallet name (null for non-transfer rows).
      counterWalletName: row.read<String?>('counter_wallet_name'),
    );
  }

  /// Parses the `group_concat` blob back into ordered chips. A malformed record
  /// (fewer than 3 fields) is skipped defensively; the name is the remainder so
  /// it is preserved even in the impossible case that it held a field separator.
  static List<TransactionRowCategory> _parseChips(String? blob) {
    if (blob == null || blob.isEmpty) {
      return const <TransactionRowCategory>[];
    }
    final List<TransactionRowCategory> chips = <TransactionRowCategory>[];
    for (final String record in blob.split(_recordSep)) {
      final List<String> f = record.split(_fieldSep);
      if (f.length < 3) {
        continue;
      }
      chips.add(
        TransactionRowCategory(
          id: int.parse(f[0]),
          colorValue: int.parse(f[1]),
          name: f.sublist(2).join(_fieldSep),
        ),
      );
    }
    return chips;
  }

  static String _placeholders(int n) => List<String>.filled(n, '?').join(',');

  /// Escapes LIKE wildcards so a user's `%`/`_`/`\` are matched literally (used
  /// with `ESCAPE '\'`).
  static String _escapeLike(String value) => value
      .replaceAll(r'\', r'\\')
      .replaceAll('%', r'\%')
      .replaceAll('_', r'\_');

  /// Raw junction rows (category id + optional allocation) for [transactionId],
  /// used to prefill the edit form's category selection and splits.
  Future<List<TransactionCategory>> getCategoryLinksForTransaction(
    int transactionId,
  ) => (select(
    transactionCategories,
  )..where((t) => t.transactionId.equals(transactionId))).get();

  /// JOIN query: the categories attached to [transactionId] via the junction
  /// table. This is the DAO-boundary join required by PROJECT_PLAN Phase 1.
  Stream<List<Category>> watchCategoriesForTransaction(int transactionId) =>
      _categoriesJoin(transactionId).watch();

  Future<List<Category>> getCategoriesForTransaction(int transactionId) =>
      _categoriesJoin(transactionId).get();

  Selectable<Category> _categoriesJoin(int transactionId) {
    final JoinedSelectStatement<HasResultSet, dynamic> query =
        select(transactionCategories).join([
          innerJoin(
            categories,
            categories.id.equalsExp(transactionCategories.categoryId),
          ),
        ])..where(transactionCategories.transactionId.equals(transactionId));
    return query.map((row) => row.readTable(categories));
  }
